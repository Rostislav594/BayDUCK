// Run with the Playwright MCP browser_run_code_unsafe filename argument.
// This file is a function expression consumed by the browser test tool, not a Node test.
async (page) => {
  const results = [], errors = [];
  const listener = error => errors.push(error.message);
  page.on('pageerror', listener);
  const check = (condition, name) => { if (!condition) throw new Error(name); results.push(name); };
  const count = async expected => page.waitForFunction(n => document.querySelectorAll('.product-card').length === n, expected);
  await page.goto('http://127.0.0.1:5173');
  await page.evaluate(() => { for (const key of Object.keys(localStorage)) if (key.startsWith('buyduck:') || key.startsWith('bayduck:')) localStorage.removeItem(key); });
  await page.reload();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  check(await page.locator('html').getAttribute('lang') === 'uk', 'Ukrainian default');
  await page.locator('.product-grid a.product-open[href="#product/court"]').first().click();
  await page.waitForFunction(() => location.hash === '#product/court');
  check(await page.locator('.product-page h1').textContent() === 'Court Essential', 'Product page opens at its own link');
  const facts = await page.locator('.product-page .item-facts').textContent();
  check(facts.includes('42 EU') && facts.includes('27,5') && facts.includes('Нові з біркою'), 'Item shows its one size, insole and condition');
  await page.locator('.product-page [data-action="add-cart"]').click();
  check(await page.locator('.header .cart-count').textContent() === '1', 'Adding the item updates cart');
  check(await page.locator('.product-page [data-action="add-cart"]').count() === 0 && await page.locator('.product-page [data-action="cart"]').count() === 1, 'A single item cannot be added twice');
  await page.goBack();
  await page.locator('.product-grid').waitFor();
  check(await page.evaluate(() => !location.hash.startsWith('#product')), 'Back returns from the product page');
  await page.locator('.product-grid [data-action="favorite"][data-id="court"]').click();
  check(await page.locator('.product-grid [data-action="favorite"][data-id="court"]').getAttribute('aria-pressed') === 'true', 'Wishlist toggles on');
  await page.locator('#language').selectOption('ru');
  check(await page.locator('.hero .search-form input').getAttribute('placeholder') === 'Какую пару ищем сегодня?', 'Russian translation');
  await page.locator('#language').selectOption('en');
  check(await page.locator('.cart-trigger').getAttribute('aria-label') === 'Bag', 'English controls');
  await page.reload();
  check(await page.locator('html').getAttribute('lang') === 'en', 'Language survives reload');
  check(await page.locator('.header .cart-count').textContent() === '1', 'Cart survives reload');
  check(await page.locator('.product-grid [data-action="favorite"][data-id="court"]').getAttribute('aria-pressed') === 'true', 'Wishlist survives reload');
  await page.locator('.cart-trigger').click();
  check(await page.locator('[data-action="quantity"]').count() === 0 && (await page.locator('.cart-total strong').textContent()).replace(/\D/g, '') === '3290', 'Cart has no quantity controls and totals the item price');
  await page.locator('[data-action="checkout"]').click();
  await page.locator('#checkout-form button[type="submit"]').click();
  check(await page.locator('#checkout-form').count() === 1, 'Required checkout fields block empty submission');
  await page.locator('[name="lastName"]').fill('Tester');
  await page.locator('[name="firstName"]').fill('Demo');
  await page.locator('[name="phone"]').fill('+380501234567');
  await page.locator('[name="city"]').fill('Kyiv');
  await page.locator('[name="point"]').fill('1');
  await page.locator('#checkout-form button[type="submit"]').click();
  check(await page.locator('.success-state').count() === 1, 'Nova Poshta checkout completes');
  check(await page.locator('.header .cart-count').textContent() === '0', 'Cart empties after the order');
  // Guests get no profile: delivery details live only inside the order the seller ships.
  check(await page.evaluate(() => Object.entries(localStorage).every(([k, v]) => k === 'buyduck:orders' || !v.includes('+380501234567'))), 'Guest details stored only in the order');
  await page.keyboard.press('Escape');
  // Each item is one of a kind: the ordered pair is sold and leaves the catalog.
  await page.goto('http://127.0.0.1:5173/#catalog');
  await count(7);
  check(await page.locator('.product-grid a[href="#product/court"]').count() === 0, 'Ordered item leaves the catalog');
  await page.goto('http://127.0.0.1:5173/#product/court');
  check(await page.locator('.product-page .sold-note').count() === 1 && await page.locator('.product-page [data-action="add-cart"]').count() === 0, 'Sold item page says it is sold');
  // Put the demo catalog back (as the owner's "Back on sale" would) for the remaining checks.
  await page.evaluate(() => localStorage.removeItem('buyduck:catalog'));
  await page.goto('http://127.0.0.1:5173/#catalog');
  await page.reload();
  await count(8);
  await page.locator('.search-form input').fill('Court');
  await page.locator('.search-form button').click();
  await count(1);
  check(await page.locator('.product-card').count() === 1, 'Search filters catalog');
  await page.locator('[data-action="reset"]').click();
  await count(8);
  check(await page.locator('.product-card').count() === 8, 'Reset restores catalog');
  await page.locator('[data-action="category"][data-value="clothing"]').click();
  await count(2);
  check(await page.locator('.product-card').count() === 2, 'Clothing filter');
  await page.locator('#sort').selectOption('price-desc');
  await page.waitForFunction(() => document.querySelector('.product-name')?.textContent === 'Weekend Hoodie');
  check(await page.locator('.product-name').first().textContent() === 'Weekend Hoodie', 'Price sorting');
  await page.goto('http://127.0.0.1:5173/#favorites');
  await count(1);
  check(await page.locator('.product-card').count() === 1, 'Wishlist page');
  await page.locator('[data-action="favorite"]').click();
  check(await page.locator('main .empty-state').count() === 1, 'Wishlist empty state');
  await page.goto('http://127.0.0.1:5173/#catalog?sale=1');
  await count(2);
  check(await page.locator('.product-card').count() === 2, 'Sale filter');
  await page.goto('http://127.0.0.1:5173/#catalog?q=%3Cscript%3Ebad%3C%2Fscript%3E');
  await page.locator('main .empty-state').waitFor();
  check(await page.locator('main .empty-state').count() === 1, 'Search safely escaped; no-result state');
  // The cart was emptied by the order; add an item again to test removal.
  await page.goto('http://127.0.0.1:5173/#product/court');
  await page.locator('.product-page [data-action="add-cart"]').click();
  await page.locator('.cart-trigger').click();
  await page.locator('[data-action="remove"]').click();
  check(await page.locator('#cart-dialog .empty-state').count() === 1, 'Removing last item shows empty bag');
  await page.keyboard.press('Escape');
  await page.locator('#language').selectOption('uk');
  await page.goto('http://127.0.0.1:5173/#home');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.hero').waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile home fits viewport');
  await page.locator('.menu-pull').click();
  check(await page.locator('.mobile-nav').isVisible(), 'Mobile menu opens');
  await page.locator('.mobile-nav a[href="#catalog?gender=women"]').click();
  await count(7);
  check(await page.locator('.menu-drawer.is-open').count() === 0 && !await page.locator('.mobile-nav').isVisible(), 'Mobile menu closes on navigation');
  check(await page.locator('.product-card').count() === 7, 'Women filter includes unisex');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile catalog fits viewport');
  await page.locator('.product-open').first().click();
  await page.locator('.product-page').waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile product page fits viewport');
  await page.goto('http://127.0.0.1:5173/#home');
  await page.locator('.hero').waitFor();
  for (const width of [320, 375, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Home fits ${width}px`);
  }
  check(errors.length === 0, 'No browser runtime errors');
  page.off('pageerror', listener);
  return { passed: results.length, results, errors };
}
